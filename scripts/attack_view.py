#!/usr/bin/env python3
"""Attack view: what a stand-in quantum attacker can do against Lamport, measured.

A quantum attacker that breaks ECDSA is simulated the usual way: by handing it the private
key. A Lamport account has no ECDSA key, so the attacker only sees published one-time
signatures. This script measures, with toy parameters (16-bit message digits, so that runs
finish in seconds), how often such an attacker forges a signature for a new message when:
  - each one-time key signed once (what the signer and the nonce key enforce), and
  - one key signed twice (what happens if reuse is not prevented).
It also records the signer refusing a second signature on one leaf.

Outputs: results/attack.json, results/attack.md, results/attack.html (self-contained page).
"""
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
sys.path.insert(0, os.path.join(ROOT, "reference"))
from lamport.attack import TOY, try_forge  # noqa: E402
from lamport.hashing import h  # noqa: E402
from lamport.params import Params  # noqa: E402
from lamport.signer import Journal, LeafReuseError, Signer  # noqa: E402
from lamport.tree import KeyTree  # noqa: E402

TRIALS = 200
MAX_TRIES = 20_000
SEED = 0x4C414D50


class StubChain:
    """Chain state stand-in for the refusal demonstration only (not a network result)."""

    def __init__(self):
        self.spent = set()

    def is_spent(self, leaf):
        return leaf in self.spent

    def is_pending(self, leaf):
        return False


def main() -> None:
    rng = random.Random(SEED)
    rb = lambda n: bytes(rng.getrandbits(8) for _ in range(n))  # noqa: E731
    results = {}
    for signed_times in (1, 2):
        tries, forged = [], 0
        for _ in range(TRIALS):
            tree = KeyTree(TOY, rb(32), rb(32), 1337)
            signed = [(m, tree.sign_with_leaf(0, m)) for m in (rb(32) for _ in range(signed_times))]
            r = try_forge(TOY, tree, 0, signed, MAX_TRIES, rng=rb)
            forged += r.forged
            if r.forged:
                tries.append(r.tries)
        tries.sort()
        results[signed_times] = {
            "trials": TRIALS, "maxTries": MAX_TRIES, "forged": forged,
            "medianTries": tries[len(tries) // 2] if tries else None,
            "tries": tries,
        }

    # Reuse refusal with real (Profile A size) Winternitz parameters on a small tree.
    p = Params(log_w=4, height=3)
    tree = KeyTree(p, rb(32), rb(32), 1337)
    chain = StubChain()
    signer = Signer(tree, chain, Journal())
    log = []
    leaf, _ = signer.sign(h(b"payment 1"))
    log.append(f"signed payment 1 with leaf {leaf}")
    chain.spent.add(leaf)
    log.append(f"chain: nonce key of leaf {leaf} now at sequence 1 (stub)")
    try:
        signer.sign_with_leaf(leaf, h(b"attacker-chosen payment"))
        log.append("ERROR: second signature produced")
    except LeafReuseError as e:
        log.append(f"refused: {e}")
    leaf2, _ = signer.sign(h(b"payment 2"))
    log.append(f"signed payment 2 with leaf {leaf2}")

    out = {
        "source": "scripts/attack_view.py",
        "toyParameters": {"logW": TOY.log_w, "messageBits": TOY.msg_bits, "chains": TOY.length},
        "oneSignaturePerKey": results[1],
        "twoSignaturesOnOneKey": results[2],
        "refusalLog": log,
        "note": "Toy parameters make the effect visible in seconds; with 256-bit digests the same attack needs far more tries but is still the reason reuse must never happen.",
    }
    with open(os.path.join(RES, "attack.json"), "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")

    r1, r2 = results[1], results[2]
    md = [
        "# Attack view (generated by scripts/attack_view.py; do not edit)", "",
        f"Toy parameters: w = {TOY.w}, {TOY.msg_bits}-bit message digits, {TOY.length} chains. {TRIALS} independent keys per row, "
        f"up to {MAX_TRIES:,} forgery attempts each.", "",
        "| what the attacker saw | keys forged | median attempts when forged |", "|---|---|---|",
        f"| one signature per one-time key | {r1['forged']} of {TRIALS} | {r1['medianTries'] if r1['medianTries'] else 'n/a'} |",
        f"| two signatures on one key | {r2['forged']} of {TRIALS} | {r2['medianTries']} |", "",
        "The toy size is deliberately weak: with 16-bit digits even one signature can be brute-forced. The point is the gap "
        "between the rows. With the real 256-bit digest, forging from one signature means finding a hash whose 67 digits all "
        "dominate the signed ones, which is believed infeasible; a second signature on the same key collapses that margin.", "",
        "Signer refusal (Profile A parameters, stub chain state):", "",
        *[f"- {line}" for line in log],
    ]
    with open(os.path.join(RES, "attack.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(RES, "attack.html"), "w") as f:
        f.write(html(out))
    print("\n".join(md))


def histogram_svg(tries: list[int]) -> str:
    """Bars: how many forged keys needed at most N attempts (bins of attempts, log2 scale)."""
    bins = [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096]
    counts = []
    for i, lo in enumerate(bins):
        hi = bins[i + 1] if i + 1 < len(bins) else 10**9
        counts.append(sum(1 for t in tries if lo <= t < hi))
    W, H, left, top, bottom = 640, 240, 44, 16, 48
    bw = (W - left - 16) / len(bins)
    cmax = max(counts) or 1
    p = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="Attempts needed to forge after two signatures on one key">']
    for t in range(0, cmax + 1, max(1, cmax // 4)):
        y = top + (H - top - bottom) * (1 - t / cmax)
        p.append(f'<line x1="{left}" x2="{W - 16}" y1="{y:.1f}" y2="{y:.1f}" class="grid"/>')
        p.append(f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" class="muted">{t}</text>')
    for i, (lo, c) in enumerate(zip(bins, counts)):
        x = left + i * bw + 2
        hgt = (H - top - bottom) * c / cmax
        y = H - bottom - hgt
        label = f"{lo}" if lo < 1024 else f"{lo // 1024}k"
        p.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{bw - 4:.1f}" height="{hgt:.1f}" rx="3" class="bar">'
                 f'<title>{c} keys forged with {lo} to {bins[i + 1] - 1 if i + 1 < len(bins) else "more"} attempts</title></rect>')
        p.append(f'<text x="{x + (bw - 4) / 2:.1f}" y="{H - bottom + 16}" text-anchor="middle" class="muted">{label}</text>')
    p.append(f'<text x="{left + (W - left) / 2:.0f}" y="{H - 8}" text-anchor="middle" class="muted">attempts (bins start at this value)</text>')
    p.append("</svg>")
    return "\n".join(p)


