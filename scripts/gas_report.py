#!/usr/bin/env python3
"""Produce every gas figure for the README from measurements.

1. Runs the Foundry gas test, which writes results/gas_raw.json (measured in the EVM).
2. Adds calldata and intrinsic-gas arithmetic from the formulas in EIP-8141, using the
   rule values in simulator/rules.json (arithmetic, not measurement; labelled so).
3. Writes results/gas.json and results/gas.md.

Usage: python3 scripts/gas_report.py [--no-run]
"""
import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")
sys.path.insert(0, os.path.join(ROOT, "reference"))
from lamport.params import Params  # noqa: E402


def rules() -> dict:
    with open(os.path.join(ROOT, "simulator", "rules.json")) as f:
        return {k: v["value"] for k, v in json.load(f).items() if not k.startswith("_")}


def run_forge() -> None:
    env = dict(os.environ, PATH=os.path.expanduser("~/.foundry/bin") + os.pathsep + os.environ["PATH"])
    subprocess.run(
        ["forge", "test", "--root", os.path.join(ROOT, "contracts"), "--match-test", "test_gas_report", "-q"],
        check=True, env=env, cwd=os.path.join(ROOT, "contracts"),
    )


def signature_data_gas(r: dict, n_bytes: int) -> dict:
    """EIP-8141 signature_data_cost for an ARBITRARY entry with empty msg (bytes priced as non-zero)."""
    standard = r["STANDARD_TOKEN_COST"] * r["TOKENS_PER_NONZERO_BYTE"] * n_bytes
    floor = r["TOTAL_COST_FLOOR_PER_TOKEN"] * r["TOKENS_PER_NONZERO_BYTE"] * n_bytes
    return {"standard": standard, "floor": floor}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-run", action="store_true", help="reuse results/gas_raw.json")
    args = ap.parse_args()
    if not args.no_run:
        run_forge()
    with open(os.path.join(RESULTS, "gas_raw.json")) as f:
        raw = json.load(f)
    r = rules()
    rows = []
    for log_w in (1, 2, 4, 8):
        m = raw[f"logW{log_w}"]
        p = Params(log_w=log_w, height=int(m["height"]))
        assert int(m["signatureBytes"]) == p.sig_bytes
        data = signature_data_gas(r, p.sig_bytes)
        rows.append({
            "w": p.w, "logW": log_w, "chains": p.length, "height": p.height,
            "signatureBytes": p.sig_bytes,
            "measured": {k: m[k] for k in ("copy", "digest", "chains", "path", "phaseSum", "fullCall")},
            "samples": int(m["samples"]),
            "arithmetic": {
                "signatureDataGasStandard": data["standard"],
                "signatureDataGasFloorTerm": data["floor"],
                "signatureVerificationGas": r["SIG_GAS_ARBITRARY"],
            },
        })
    out = {
        "source": "measured by contracts/test/Gas.t.sol; arithmetic from simulator/rules.json",
        "solc": raw.get("solc"),
        "rows": rows,
    }
    with open(os.path.join(RESULTS, "gas.json"), "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")

    md = ["# Gas per verification phase (generated by scripts/gas_report.py; do not edit)", "",
          f"Compiler: {raw.get('solc')}. Tree height 10. Each row: mean over {rows[0]['samples']} random messages "
          "(min to max in brackets). Measured in the EVM with gasleft() around each phase of the library.", "",
          "| w | chains | signature bytes | copy | digest | chains + leaf hash | path (10 levels) | library call total | fits 100,000? |",
          "|---|---|---|---|---|---|---|---|---|"]
    for row in rows:
        ms = row["measured"]
        f = lambda k: f"{int(ms[k]['mean']):,} ({int(ms[k]['min']):,} to {int(ms[k]['max']):,})"  # noqa: E731
        fits = "yes" if int(ms["fullCall"]["max"]) + r["SIG_GAS_ARBITRARY"] < r["MAX_VERIFY_GAS"] else "no"
        md.append(f"| {row['w']} | {row['chains']} | {row['signatureBytes']:,} | {int(ms['copy']['mean']):,} | "
                  f"{int(ms['digest']['mean']):,} | {f('chains')} | {f('path')} | {f('fullCall')} | {fits} (library only) |")
    md += ["", "## Signature bytes as transaction data (arithmetic from the EIP-8141 formulas, not measured)", "",
           "ARBITRARY bytes with empty `msg` are priced as all non-zero. Standard cost is 16 gas per byte. "
           "The calldata floor term is 64 gas per byte; the transaction pays the larger of its standard total and its floor total. "
           "My reading of rule 6 is that neither counts toward MAX_VERIFY_GAS (OPEN_QUESTIONS Q1, unconfirmed).", "",
           "| w | signature bytes | standard data gas | floor term |", "|---|---|---|---|"]
    for row in rows:
        a = row["arithmetic"]
        md.append(f"| {row['w']} | {row['signatureBytes']:,} | {a['signatureDataGasStandard']:,} | {a['signatureDataGasFloorTerm']:,} |")
    md += ["", "The frame-level figure (frame entry, TXPARAM, SIGDATACOPY, APPROVE, nonce-key checks) is not in this table: "
           "it needs an EIP-8141 client (docs/DEVNET_RUNBOOK.md)."]
    with open(os.path.join(RESULTS, "gas.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
