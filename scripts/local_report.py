#!/usr/bin/env python3
"""Summarise results/local/*.json (raw responses from the local chain) into results/local/summary.md."""
import glob
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "results", "local")


def frames(sim):
    r = (sim or {}).get("result")
    if not r:
        return f"error: {((sim or {}).get('error') or {}).get('message', '?')}"
    out = []
    for i, f in enumerate(r.get("frames") or []):
        g = f.get("gasUsed")
        g = int(g, 16) if isinstance(g, str) else g
        out.append(f"frame {i}: {'ok' if f.get('succeeded') else 'failed'}, {g:,} gas")
    return "; ".join(out) or json.dumps(r)[:120]


def verdict(resp):
    if resp is None:
        return "not sent"
    if "result" in resp:
        return f"ACCEPTED into the sidecar mempool ({str(resp['result'])[:18]}...)"
    return f"REFUSED: {(resp.get('error') or {}).get('message', '?')[:220]}"


def short(state: dict) -> str:
    (k, v), = state.items()
    return f"{'key sequence' if k == 'nonceManagerSlot' else 'account nonce'} {int(v, 16)}"


def main():
    rows = []
    cal = []
    for mode in ("keyed", "legacy"):
        p = os.path.join(D, f"calibration_{mode}.json")
        if os.path.exists(p):
            c = json.load(open(p))
            g = c["gas"]
            cal.append(f"| Profile A VERIFY frame, {mode} nonce | {len(g)} | {min(g):,} | {sum(g) // len(g):,} | {max(g):,} | `calibration_{mode}.json` |")
    for path in sorted(glob.glob(os.path.join(D, "*.json"))):
        if os.path.basename(path).startswith(("calibration_", "deploy_state", "inclusion-", "node-xmss")):
            continue
        d = json.load(open(path))
        name = d.get("experiment") or ("Profile B payment" if d.get("profile") == "B" else f"Profile A payment ({d.get('nonceMode', 'keyed')} nonce)")
        limit = d.get("verifyLimit")
        rows.append((name, frames(d.get("simulation")), verdict(d.get("response")), limit, os.path.basename(path)))
    head = ["# Local chain results (generated by scripts/local_report.py; do not edit)", "",
            "LOCAL ethrex `eip8141-tracer` + local sidecar, not the public devnet. The first table holds ethrex simulations "
            "(real EIP-8141 opcodes) and the sidecar's admission verdicts; the inclusion table uses blocks built by "
            "scripts/local_blocks.py through the Engine API. The probes' second frame fails for an unrelated reason: it "
            "sends 1 wei to a new address with no state gas; only their VERIFY frame matters.", "",
            "| experiment | ethrex simulation (per frame) | sidecar verdict | file |", "|---|---|---|---|"]
    body = [f"| {n} | {f} | {v} | `{p}` |" for n, f, v, _, p in rows]
    if cal:
        body += ["", "Real VERIFY frame gas on ethrex (simulation, high limit, each sample a fresh leaf):", "",
                 "| frame | samples | min | mean | max | file |", "|---|---|---|---|---|---|", *cal]
    inc = []
    for mode in ("keyed", "legacy"):
        p = os.path.join(D, f"inclusion-{mode}.json")
        if not os.path.exists(p):
            continue
        d = json.load(open(p))
        st = (d.get("receiptNode") or {}).get("result") or {}
        msg = lambda r: (r.get("error") or {}).get("message") or ((r.get("result") or {}).get("executionError")) or str(r.get("result"))[:40]  # noqa: E731
        inc.append(f"| Profile A, {mode} nonce | leaf {d['leaf']} | block {d['block1']['number']}, status {st.get('status')} | "
                   f"{short(d['leafStateBefore'])} -> {short(d['leafStateAfter'])} | node: {msg(d['reuseSimulation'])}; "
                   f"sidecar: {msg(d['reuseSidecar'])} | {msg(d['reuseNextSeqSidecar'])} | {d['reuseSigner']}; next leaf {d['nextLeaf']} | `inclusion-{mode}.json` |")
    px = os.path.join(D, "inclusion-xmss-raised-node-budget.json")
    if os.path.exists(px):
        d = json.load(open(px))
        st = (d.get("receipt") or {}).get("result") or {}
        g = int(d["simulation"]["result"]["frames"][0]["gasUsed"], 16)
        inc.append(f"| Profile B, node budget raised to 1,000,000 (no sidecar) | leaf {d['leaf']} | block {d['block']['number']}, status {st.get('status')}, VERIFY {g:,} gas | "
                   f"slot {int(d['slotBefore'], 16)} -> {int(d['slotAfter'], 16)} | n/a | n/a | n/a | `inclusion-xmss-raised-node-budget.json` |")
    pp = os.path.join(D, "inclusion-xmss-patched-sidecar.json")
    if os.path.exists(pp):
        d = json.load(open(pp))
        st = (d.get("receipt") or {}).get("result") or {}
        g = int(d["simulation"]["result"]["frames"][0]["gasUsed"], 16)
        inc.append(f"| Profile B through the PATCHED sidecar (budget 1,000,000, precompiles listed; docs/RULE_FINDINGS.md) | leaf {d['leaf']} | "
                   f"accepted by the sidecar, relayed, block {d['block']['number']}, status {st.get('status')}, VERIFY {g:,} gas | "
                   f"slot {int(d['slotBefore'], 16)} -> {int(d['slotAfter'], 16)} | n/a | n/a | n/a | `inclusion-xmss-patched-sidecar.json` |")
    pd = os.path.join(D, "node-xmss-default-budget.json")
    if os.path.exists(pd):
        d = json.load(open(pd))
        inc.append(f"| Profile B, default node budget 100,000 (no sidecar) | leaf {d['leaf']} | refused at submission: {(d['nodeSubmit'].get('error') or {}).get('message')} | n/a | n/a | n/a | n/a | `node-xmss-default-budget.json` |")
    if inc:
        body += ["", "Inclusion on the local chain (blocks built by scripts/local_blocks.py through the Engine API):", "",
                 "| transaction | leaf | included | leaf state before -> after | same leaf again | same leaf, next sequence | signer | file |",
                 "|---|---|---|---|---|---|---|---|", *inc]
    rp = os.path.join(D, "rotation", "summary.json")
    if os.path.exists(rp):
        r = json.load(open(rp))
        ro, pay, bad = r["rotation"], r["paymentEpoch1"], r["paymentUnregisteredEpoch2"]
        body += ["", "Key rotation on the local chain (`rotation/summary.json`):", "",
                 f"- Rotation signed with epoch-0 leaf {ro['leafUsed']}: block {ro['block']['number']}, status {ro['receiptStatus']}; "
                 f"last epoch now {ro['lastEpochAfter']}; slot 1 holds the new tree's commitment: {ro['slot1Matches']}.",
                 f"- Payment with the epoch-1 key (leaf {pay['leaf']}): block {pay['block']['number']}, status {pay['receiptStatus']}, VERIFY {pay['verifyGas']:,} gas.",
                 f"- Payment with an unregistered epoch-2 key: node {bad['simulation']}; sidecar: {((bad['sidecar'] or {}).get('error') or {}).get('message')}."]
    dp = os.path.join(D, "deploy_state.json")
    if os.path.exists(dp):
        ds = json.load(open(dp))
        body += ["", f"Deploy + self_verify in one transaction: the deploy frame needs between {ds['deployStateGasFails']:,} and "
                 f"{ds['deployStateGasSucceeds']:,} state gas ({ds['accountRuntimeBytes']:,} runtime bytes x {ds['costPerStateByte']:,} = "
                 f"{ds['runtimeBytesTimesCpsb']:,}); the public cap is {ds['publicMaxVerifyStateGas']:,}: {ds['verdict']} (`deploy_state.json`)."]
    open(os.path.join(D, "summary.md"), "w").write("\n".join(head + body) + "\n")
    readme = os.path.join(ROOT, "README.md")
    text = open(readme).read()
    a, b = "<!-- local:start -->", "<!-- local:end -->"
    if a in text and b in text:
        block = "\n".join([a, *head[2:], *body, "", "Raw responses: results/local/. Generated by scripts/local_report.py.", b])
        open(readme, "w").write(text[: text.index(a)] + block + text[text.index(b) + len(b):])
    print("\n".join(head + body))


if __name__ == "__main__":
    main()
